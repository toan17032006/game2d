[CmdletBinding()]
param(
    [string[]]$Case = @()
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

. (Join-Path $PSScriptRoot 'lib\agent-runtime.ps1')

$repoRoot = Get-AgentRepoRoot
$tasksRoot = Join-Path $repoRoot '.agent\tasks'
$tempRoot = Join-Path $tasksRoot '_temp_regression'
$allCases = @(
    'CASE-001', 'CASE-002', 'CASE-003', 'CASE-004', 'CASE-005', 'CASE-006', 'CASE-007',
    'CASE-008', 'CASE-009', 'CASE-010', 'CASE-011', 'CASE-012', 'CASE-013'
)

$selected = @($Case | ForEach-Object { $_.Trim().ToUpperInvariant() } | Where-Object { $_ -ne '' })
if ($selected.Count -eq 0) { $selected = $allCases }
foreach ($requested in $selected) {
    if ($allCases -notcontains $requested) {
        Write-Output "FAIL: unknown regression case '$requested'"
        exit 1
    }
}

$results = [System.Collections.Generic.List[PSCustomObject]]::new()

function Test-Selected([string]$Id) {
    return ($selected -contains $Id)
}

function Add-Result([string]$Id, [string]$Description, [int]$ExpectedExit, [int]$ActualExit) {
    $passed = ($ExpectedExit -eq $ActualExit)
    [void]$results.Add([PSCustomObject]@{
        CaseId       = $Id
        Description  = $Description
        ExpectedExit = $ExpectedExit
        ActualExit   = $ActualExit
        Result       = if ($passed) { 'PASS' } else { 'FAIL' }
    })
}

function Invoke-AgentScript {
    param(
        [Parameter(Mandatory = $true)][string]$ScriptName,
        [string[]]$Arguments = @(),
        [int]$TimeoutSeconds = 600
    )

    $scriptPath = Join-Path $PSScriptRoot $ScriptName
    $hostPath = Get-AgentPowerShellPath
    $hostArguments = @('-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', $scriptPath) + $Arguments
    return Invoke-ExternalProcess -FilePath $hostPath -Arguments $hostArguments -WorkingDirectory $repoRoot -TimeoutSeconds $TimeoutSeconds
}

function New-MockTask {
    param(
        [Parameter(Mandatory = $true)][string]$TargetDir,
        [Parameter(Mandatory = $true)][string]$MockTaskId,
        [switch]$WithoutTestCommand,
        [string]$TestCommand = '',
        [string]$NotApplicableReason = ''
    )

    $null = New-Item -ItemType Directory -Path $TargetDir -Force

    @"
# Prompt
Input: DIRECT
## References
- /AGENTS.md
"@ | Out-File -LiteralPath (Join-Path $TargetDir 'prompt.md') -Encoding utf8

    @"
# Task
- Task ID: `$MockTaskId`
- Status: EXECUTING
## Acceptance criteria
| ID | Criterion | Required evidence |
| --- | --- | --- |
| AC-001 | Mock criteria | Mock evidence |
## References
- /AGENTS.md
"@ | Out-File -LiteralPath (Join-Path $TargetDir 'task.md') -Encoding utf8

    $specBody = @"
# Specification
## Constraints
- Mock task generated by the regression suite.
"@
    if (-not $WithoutTestCommand) {
        if (-not [string]::IsNullOrWhiteSpace($NotApplicableReason)) {
            $specBody += "`n## Product Verification: not-applicable`n- not-applicable: $NotApplicableReason`n"
        } else {
            if ([string]::IsNullOrWhiteSpace($TestCommand)) {
                $TestCommand = 'powershell -NoProfile -ExecutionPolicy Bypass -Command "exit 0"'
            }
            $specBody += "`n## Test Command`n$TestCommand`n"
        }
    }
    $specBody += "`n## References`n- /AGENTS.md`n"
    $specBody | Out-File -LiteralPath (Join-Path $TargetDir 'spec.md') -Encoding utf8

    @"
# Plan
## Phases
| ID | Action | Status |
| --- | --- | --- |
| P1 | Initial phase | DONE |
## Rollback
Rollback plan
## Checkpoints
Checkpoint plan
## References
- /AGENTS.md
"@ | Out-File -LiteralPath (Join-Path $TargetDir 'plan.md') -Encoding utf8

    @"
# Handoff Checkpoint
- Task ID: `$MockTaskId`
- Status: EXECUTING
## Current phase
P1
## Last completed
Setup
## Next action
Verify
## Decisions
None
## Changed files
- None
## Validation
None
## Blockers
None
## References
- /AGENTS.md
"@ | Out-File -LiteralPath (Join-Path $TargetDir 'handoff.md') -Encoding utf8

    @"
# Verification
- Task ID: `$MockTaskId`
- Status: ``COMPLETED``
## Acceptance coverage
| ID | Result | Evidence |
| --- | --- | --- |
| AC-001 | PASS | Verified in regression test |
## Commands
| Command | Result | Evidence |
| --- | --- | --- |
| ``echo test`` | PASS | Mock output |
## References
- /AGENTS.md
"@ | Out-File -LiteralPath (Join-Path $TargetDir 'verification.md') -Encoding utf8

    @"
# Evaluation
- Task ID: `$MockTaskId`
- Status: ``COMPLETED``
| Dimension | Score 0-5 | Result | Evidence |
| --- | --- | --- | --- |
| Input fidelity | 5/5 | PASS | High fidelity input |
| Output correctness | 5/5 | PASS | Output is fully correct |
| Verification quality | 5/5 | PASS | Verification is complete |
## Final result

``PASS``

## References
- /AGENTS.md
"@ | Out-File -LiteralPath (Join-Path $TargetDir 'evaluation.md') -Encoding utf8
}

# Cleanup existing temp directory if any
if (Test-Path -LiteralPath $tempRoot) {
    Remove-Item -LiteralPath $tempRoot -Recurse -Force
}
$null = New-Item -ItemType Directory -Path $tempRoot -Force

$createdTasks = [System.Collections.Generic.List[string]]::new()
$lintProbe = Join-Path $PSScriptRoot '_temp_lint_probe.ps1'

try {
    # -----------------------------------------------------------------
    # CASE-001: Missing required task file (spec.md) -> FAIL (1)
    # -----------------------------------------------------------------
    if (Test-Selected 'CASE-001') {
        $case1Dir = Join-Path $tasksRoot 'TASK-20990101-001'
        New-MockTask -TargetDir $case1Dir -MockTaskId 'TASK-20990101-001'
        [void]$createdTasks.Add($case1Dir)
        Remove-Item -LiteralPath (Join-Path $case1Dir 'spec.md') -Force
        $result = Invoke-AgentScript -ScriptName 'validate-task.ps1' -Arguments @('-TaskId', 'TASK-20990101-001', '-Mode', 'preflight')
        Add-Result 'CASE-001' 'Missing required task file (spec.md) fails validator' 1 $result.ExitCode
        Remove-Item -LiteralPath $case1Dir -Recurse -Force
    }

    # -----------------------------------------------------------------
    # CASE-002: Missing acceptance evidence for AC-001 -> FAIL (1)
    # -----------------------------------------------------------------
    if (Test-Selected 'CASE-002') {
        $case2Dir = Join-Path $tasksRoot 'TASK-20990101-002'
        New-MockTask -TargetDir $case2Dir -MockTaskId 'TASK-20990101-002'
        [void]$createdTasks.Add($case2Dir)
        @"
# Verification
- Task ID: `TASK-20990101-002`
- Status: COMPLETED
## Acceptance coverage
| ID | Result | Evidence |
| --- | --- | --- |
## Commands
| Command | Result | Evidence |
| --- | --- | --- |
| `echo test` | PASS | Mock output |
## References
- /AGENTS.md
"@ | Out-File -LiteralPath (Join-Path $case2Dir 'verification.md') -Encoding utf8
        $result = Invoke-AgentScript -ScriptName 'verify-task.ps1' -Arguments @('-TaskId', 'TASK-20990101-002')
        Add-Result 'CASE-002' 'Missing acceptance evidence fails verifier' 1 $result.ExitCode
        Remove-Item -LiteralPath $case2Dir -Recurse -Force
    }

    # -----------------------------------------------------------------
    # CASE-003: Incomplete evaluation score -> FAIL (1)
    # -----------------------------------------------------------------
    if (Test-Selected 'CASE-003') {
        $case3Dir = Join-Path $tasksRoot 'TASK-20990101-003'
        New-MockTask -TargetDir $case3Dir -MockTaskId 'TASK-20990101-003'
        [void]$createdTasks.Add($case3Dir)
        @"
# Evaluation
- Task ID: `TASK-20990101-003`
- Status: COMPLETED
| Dimension | Score 0-5 | Result | Evidence |
| --- | --- | --- | --- |
| Input fidelity | 5/5 | PASS | Valid input |
## Final result
`PASS`
## References
- /AGENTS.md
"@ | Out-File -LiteralPath (Join-Path $case3Dir 'evaluation.md') -Encoding utf8
        $result = Invoke-AgentScript -ScriptName 'verify-task.ps1' -Arguments @('-TaskId', 'TASK-20990101-003')
        Add-Result 'CASE-003' 'Missing evaluation dimension fails verifier' 1 $result.ExitCode
        Remove-Item -LiteralPath $case3Dir -Recurse -Force
    }

    # -----------------------------------------------------------------
    # CASE-004: Empty command evidence -> FAIL (1)
    # -----------------------------------------------------------------
    if (Test-Selected 'CASE-004') {
        $case4Dir = Join-Path $tasksRoot 'TASK-20990101-004'
        New-MockTask -TargetDir $case4Dir -MockTaskId 'TASK-20990101-004'
        [void]$createdTasks.Add($case4Dir)
        @"
# Verification
- Task ID: `TASK-20990101-004`
- Status: COMPLETED
## Acceptance coverage
| ID | Result | Evidence |
| --- | --- | --- |
| AC-001 | PASS | Verified in regression test |
## Commands
| Command | Result | Evidence |
| --- | --- | --- |
## References
- /AGENTS.md
"@ | Out-File -LiteralPath (Join-Path $case4Dir 'verification.md') -Encoding utf8
        $result = Invoke-AgentScript -ScriptName 'verify-task.ps1' -Arguments @('-TaskId', 'TASK-20990101-004')
        Add-Result 'CASE-004' 'Missing command evidence fails verifier' 1 $result.ExitCode
        Remove-Item -LiteralPath $case4Dir -Recurse -Force
    }

    # -----------------------------------------------------------------
    # CASE-005: Fully compliant task -> PASS (0)
    # -----------------------------------------------------------------
    if (Test-Selected 'CASE-005') {
        $case5Dir = Join-Path $tasksRoot 'TASK-20990101-005'
        New-MockTask -TargetDir $case5Dir -MockTaskId 'TASK-20990101-005'
        [void]$createdTasks.Add($case5Dir)
        $specCase5 = Join-Path $case5Dir 'spec.md'
        @"
# Specification
## Test Command
powershell -NoProfile -ExecutionPolicy Bypass -Command "exit 0"
## Approved Documentation Changes
- `/.agent/evaluations/cases/README.md`
## References
- /AGENTS.md
"@ | Out-File -LiteralPath $specCase5 -Encoding utf8

        $result = Invoke-AgentScript -ScriptName 'run-quality-gates.ps1' -Arguments @('-TaskId', 'TASK-20990101-005', '-Mode', 'final')
        if ($result.ExitCode -ne 0) {
            @($result.StdOut) + @($result.StdErr) | ForEach-Object { Write-Output "  CASE-005: $_" }
        }
        Add-Result 'CASE-005' 'Compliant task passes final quality gates' 0 $result.ExitCode
        Remove-Item -LiteralPath $case5Dir -Recurse -Force
    }

    # -----------------------------------------------------------------
    # CASE-006: Unauthorized doc edit boundary violation -> FAIL (1)
    # -----------------------------------------------------------------
    if (Test-Selected 'CASE-006') {
        $case6Dir = Join-Path $tasksRoot 'TASK-20990101-006'
        New-MockTask -TargetDir $case6Dir -MockTaskId 'TASK-20990101-006'
        [void]$createdTasks.Add($case6Dir)
        $unauthDoc = Join-Path $repoRoot 'docs\01-product\_temp_unauth_test.md'
        @"
# Unauthorized
## References
- /AGENTS.md
"@ | Out-File -LiteralPath $unauthDoc -Encoding utf8

        $result = Invoke-AgentScript -ScriptName 'check-doc-boundaries.ps1' -Arguments @('-TaskId', 'TASK-20990101-006')
        Add-Result 'CASE-006' 'Unauthorized doc edit fails boundary check' 1 $result.ExitCode

        if (Test-Path -LiteralPath $unauthDoc) { Remove-Item -LiteralPath $unauthDoc -Force }
        Remove-Item -LiteralPath $case6Dir -Recurse -Force
    }

    # -----------------------------------------------------------------
    # CASE-007: Broken markdown link -> FAIL (1)
    # -----------------------------------------------------------------
    if (Test-Selected 'CASE-007') {
        $brokenLinkDir = Join-Path $tempRoot 'broken_links'
        $null = New-Item -ItemType Directory -Path $brokenLinkDir -Force
        @"
# Broken File
[Dead Link](/docs/non-existent-file-12345.md)
"@ | Out-File -LiteralPath (Join-Path $brokenLinkDir 'broken.md') -Encoding utf8

        $result = Invoke-AgentScript -ScriptName 'test-markdown-links.ps1' -Arguments @('-Path', $brokenLinkDir)
        Add-Result 'CASE-007' 'Broken markdown link fails link checker' 1 $result.ExitCode

        # Remove immediately: later cases run repository-wide link checks and
        # must not inherit this deliberate fixture.
        Remove-Item -LiteralPath $brokenLinkDir -Recurse -Force
    }

    # -----------------------------------------------------------------
    # CASE-008: Task without a product verification declaration -> FAIL (1)
    # -----------------------------------------------------------------
    if (Test-Selected 'CASE-008') {
        $case8Dir = Join-Path $tasksRoot 'TASK-20990101-008'
        New-MockTask -TargetDir $case8Dir -MockTaskId 'TASK-20990101-008' -WithoutTestCommand
        [void]$createdTasks.Add($case8Dir)
        $result = Invoke-AgentScript -ScriptName 'verify-product.ps1' -Arguments @('-TaskId', 'TASK-20990101-008')
        Add-Result 'CASE-008' 'Missing product verification declaration fails product harness' 1 $result.ExitCode
        Remove-Item -LiteralPath $case8Dir -Recurse -Force
    }

    # -----------------------------------------------------------------
    # CASE-009: Explicit not-applicable declaration -> PASS (0, SKIPPED)
    # -----------------------------------------------------------------
    if (Test-Selected 'CASE-009') {
        $case9Dir = Join-Path $tasksRoot 'TASK-20990101-009'
        New-MockTask -TargetDir $case9Dir -MockTaskId 'TASK-20990101-009' `
            -NotApplicableReason 'Documentation-only task; verified by the Markdown link checker.'
        [void]$createdTasks.Add($case9Dir)
        $result = Invoke-AgentScript -ScriptName 'verify-product.ps1' -Arguments @('-TaskId', 'TASK-20990101-009')
        $artifactPath = Join-Path $case9Dir 'logs\product-verification.json'
        $recordedStatus = ''
        if (Test-Path -LiteralPath $artifactPath -PathType Leaf) {
            $artifact = Get-Content -LiteralPath $artifactPath -Raw | ConvertFrom-Json
            $recordedStatus = [string]$artifact.status
        }
        $actual = if ($result.ExitCode -eq 0 -and $recordedStatus -eq 'SKIPPED') { 0 } else { 1 }
        if ($actual -ne 0) {
            @($result.StdOut) + @($result.StdErr) | ForEach-Object { Write-Output "  CASE-009: $_" }
        }
        Add-Result 'CASE-009' 'Explicit not-applicable declaration records SKIPPED evidence' 0 $actual
        Remove-Item -LiteralPath $case9Dir -Recurse -Force
    }

    # -----------------------------------------------------------------
    # CASE-010: Declared product command that fails -> FAIL (1)
    # -----------------------------------------------------------------
    if (Test-Selected 'CASE-010') {
        $case10Dir = Join-Path $tasksRoot 'TASK-20990101-010'
        New-MockTask -TargetDir $case10Dir -MockTaskId 'TASK-20990101-010' `
            -TestCommand 'powershell -NoProfile -ExecutionPolicy Bypass -Command "exit 7"'
        [void]$createdTasks.Add($case10Dir)
        $result = Invoke-AgentScript -ScriptName 'verify-product.ps1' -Arguments @('-TaskId', 'TASK-20990101-010')
        Add-Result 'CASE-010' 'Failing product command fails product harness' 1 $result.ExitCode
        Remove-Item -LiteralPath $case10Dir -Recurse -Force
    }

    # -----------------------------------------------------------------
    # CASE-011: Noisy git stderr is diagnostic, not a boundary failure
    # -----------------------------------------------------------------
    if (Test-Selected 'CASE-011') {
        $case11Dir = Join-Path $tasksRoot 'TASK-20990101-011'
        New-MockTask -TargetDir $case11Dir -MockTaskId 'TASK-20990101-011'
        [void]$createdTasks.Add($case11Dir)

        $noiseProbe = Invoke-ExternalProcess -FilePath 'git' `
            -Arguments @('-C', $repoRoot, 'status', '--porcelain') `
            -WorkingDirectory $repoRoot -TimeoutSeconds 60 `
            -EnvironmentVariables @{ GIT_TRACE = '1' }

        $previousTrace = $env:GIT_TRACE
        $env:GIT_TRACE = '1'
        try {
            $result = Invoke-AgentScript -ScriptName 'check-doc-boundaries.ps1' -Arguments @('-TaskId', 'TASK-20990101-011')
        } finally {
            if ($null -eq $previousTrace) { Remove-Item Env:\GIT_TRACE -ErrorAction SilentlyContinue } else { $env:GIT_TRACE = $previousTrace }
        }

        $noiseObserved = (@($noiseProbe.StdErr).Count -gt 0)
        if (-not $noiseObserved) {
            Write-Output '  CASE-011: GIT_TRACE produced no stderr noise; stderr tolerance was not exercised'
        }
        $actual = if ($result.ExitCode -eq 0 -and $noiseObserved) { 0 } else { 1 }
        if ($actual -ne 0) {
            @($result.StdOut) + @($result.StdErr) | ForEach-Object { Write-Output "  CASE-011: $_" }
        }
        Add-Result 'CASE-011' 'Noisy git stderr does not fail the boundary check' 0 $actual
        Remove-Item -LiteralPath $case11Dir -Recurse -Force
    }

    # -----------------------------------------------------------------
    # CASE-012: Lint rule catches an unguarded native git call -> FAIL (1)
    # -----------------------------------------------------------------
    if (Test-Selected 'CASE-012') {
        # Fixture is assembled from fragments so this runner itself stays
        # compliant with LINT-004 while still exercising the rule.
        $probeLines = @("`$ErrorActionPreference = 'Stop'", ('& ' + 'git status --porcelain'))
        $probeLines | Out-File -LiteralPath $lintProbe -Encoding utf8
        try {
            $result = Invoke-AgentScript -ScriptName 'test-agent-lint.ps1'
        } finally {
            if (Test-Path -LiteralPath $lintProbe) { Remove-Item -LiteralPath $lintProbe -Force }
        }
        if ($result.ExitCode -eq 0) {
            Write-Output '  CASE-012: lint accepted a direct git invocation'
        }
        Add-Result 'CASE-012' 'Lint rejects unguarded native git invocations' 1 $result.ExitCode
        if (Test-Path -LiteralPath $lintProbe) { Remove-Item -LiteralPath $lintProbe -Force }
    }

    # -----------------------------------------------------------------
    # CASE-013: Lifecycle model check -> PASS (0)
    # -----------------------------------------------------------------
    if (Test-Selected 'CASE-013') {
        $result = Invoke-AgentScript -ScriptName 'model-check-task-lifecycle.ps1'
        if ($result.ExitCode -ne 0) {
            @($result.StdOut) + @($result.StdErr) | ForEach-Object { Write-Output "  CASE-013: $_" }
        }
        Add-Result 'CASE-013' 'Lifecycle model check passes with all invariants' 0 $result.ExitCode
    }
} finally {
    if (Test-Path -LiteralPath $lintProbe) { Remove-Item -LiteralPath $lintProbe -Force }
    if (Test-Path -LiteralPath $tempRoot) {
        Remove-Item -LiteralPath $tempRoot -Recurse -Force
    }
    foreach ($leftover in $createdTasks) {
        if (Test-Path -LiteralPath $leftover) { Remove-Item -LiteralPath $leftover -Recurse -Force }
    }
    # Never leave regression scaffolding behind, even after a mid-suite abort.
    Get-ChildItem -LiteralPath $tasksRoot -Directory -Filter 'TASK-2099*' -ErrorAction SilentlyContinue |
        ForEach-Object { Remove-Item -LiteralPath $_.FullName -Recurse -Force }
}

Write-Output '=== Regression Test Results ==='
$results | Format-Table -AutoSize CaseId, ExpectedExit, ActualExit, Result, Description

$failedCases = @($results | Where-Object { $_.Result -ne 'PASS' })
if ($failedCases.Count -gt 0) {
    Write-Output 'FAIL: One or more regression test cases failed.'
    foreach ($failed in $failedCases) {
        Write-Output "- $($failed.CaseId): $($failed.Description) (expected exit $($failed.ExpectedExit), got $($failed.ActualExit))"
    }
    exit 1
}

Write-Output "PASS: All $($results.Count) selected regression test cases passed."
exit 0
